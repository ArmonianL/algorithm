/*
================ SG 函数核心 =================
适用：有限、无环、正常玩法的公平组合游戏（无路可走者输）。
【一、SG 本身】
1. SG(x) = mex{SG(y) | x 能一步到达 y}，
   mex 表示集合中“没有出现的最小非负整数”。
2. x 是“游戏状态”，SG(x) 是这个状态对应的非负整数；
   状态和 SG 值一定要区分。
3. 由终局开始向上归纳可得：
   SG(x) == 0  <=> 当前玩家必败；
   SG(x) != 0  <=> 当前玩家必胜。
4. 多个互相独立的子游戏组合时，SG 组合定理：
   SG_total = SG1 ^ SG2 ^ ... ^ SGn。
5. 因此做题时：
   SG_total == 0  -> 先手必败；
   SG_total != 0  -> 先手必胜。

【二、Nim 与 SG 的关系】
6. 单堆 Nim 中，若有 k 个石子，则 SG(k) = k。
7. 因此 SG(x) = k 可以解释为：
   状态 x 在“组合游戏意义”下等价于一堆 k 个石子的 Nim。
8. “等价于 Nim”主要是对 SG 值含义的理论解释；
   实际做题已有 SG 组合定理后，直接求各子游戏 SG 并异或即可，
   不需要真的把游戏转化成 Nim。

核心逻辑：
mex 定义
-> SG=0/非0 判断单个状态胜负
-> 独立子游戏的 SG 可以异或
-> 直接判断整个组合游戏胜负

Nim 的作用：
SG(Nim(k)) = k
-> 给 SG(x)=k 一个直观解释：x ~ Nim(k)。
========================================================
*/